export function createIgnoreMatcher(patterns: string[]): (path: string) => boolean {
  const matcher = picomatch(patterns.length ? patterns : ['__never__'], { dot: true });
  return (path: string) => matcher(path);
}

const GENERATED_MARKERS = /(@generated|DO NOT EDIT|auto-generated|autogenerated by|Code generated by .* DO NOT EDIT)/i;

/** Detect generated files by content header or minified shape. */
export function looksGenerated(content: string | null | undefined): boolean {
  if (!content) return false;
  const head = content.slice(0, 600);
  if (GENERATED_MARKERS.test(head)) return true;
  const lines = content.split('\n');
  if (lines.length <= 3 && content.length > 5000) return true; // minified bundle
  return false;
}
