import picomatch from 'picomatch';
import { parse as parseYaml } from 'yaml';
import { z } from 'zod';
import type { FindingSeverity } from '../db/schema.js';

export const SEVERITY_ORDER: FindingSeverity[] = ['info', 'low', 'medium', 'high', 'critical'];
export const severityRank = (s: FindingSeverity) => SEVERITY_ORDER.indexOf(s);

export const REVIEW_PASS_IDS = ['bugs', 'security', 'performance', 'readability'] as const;
export type ReviewPassId = (typeof REVIEW_PASS_IDS)[number];

export const repoConfigSchema = z
  .object({
    /** Toggle individual review passes. */
    passes: z
      .object({
        bugs: z.boolean().default(true),
        security: z.boolean().default(true),
        performance: z.boolean().default(true),
        readability: z.boolean().default(true),
      })
      .partial()
      .default({}),
    rules: z
      .object({
        /** Rule ids that should never be reported (e.g. `readability/console-log`). */
        disabled: z.array(z.string()).default([]),
        /** Free-form team guidelines appended to every review prompt. */
        instructions: z.array(z.string().max(500)).max(20).default([]),
      })
      .default({ disabled: [], instructions: [] }),
    ignore: z.array(z.string()).default([]),
    severity_threshold: z.enum(['info', 'low', 'medium', 'high', 'critical']).default('low'),
    tone: z.enum(['friendly', 'neutral', 'strict']).default('neutral'),
    max_findings: z.number().int().min(1).max(200).default(30),
    max_file_changed_lines: z.number().int().positive().optional(),
    post_summary: z.boolean().default(true),
    post_inline_comments: z.boolean().default(true),
  })
  .strict();

export type RepoConfigInput = z.input<typeof repoConfigSchema>;

export interface RepoConfig {
  passes: Record<ReviewPassId, boolean>;
  rules: { disabled: string[]; instructions: string[] };
  ignore: string[];
  severityThreshold: FindingSeverity;
  tone: 'friendly' | 'neutral' | 'strict';
  maxFindings: number;
  maxFileChangedLines?: number;
  postSummary: boolean;
  postInlineComments: boolean;
}

export const CONFIG_FILE_NAME = '.codesentinel.yml';

function normalize(parsed: z.output<typeof repoConfigSchema>): RepoConfig {
  return {
    passes: {
      bugs: parsed.passes.bugs ?? true,
      security: parsed.passes.security ?? true,
      performance: parsed.passes.performance ?? true,
      readability: parsed.passes.readability ?? true,
    },
    rules: parsed.rules,
    ignore: parsed.ignore,
    severityThreshold: parsed.severity_threshold,
    tone: parsed.tone,
    maxFindings: parsed.max_findings,
    maxFileChangedLines: parsed.max_file_changed_lines,
    postSummary: parsed.post_summary,
    postInlineComments: parsed.post_inline_comments,
  };
}

export const DEFAULT_CONFIG: RepoConfig = normalize(repoConfigSchema.parse({}));

export interface ConfigParseResult {
  config: RepoConfig;
  source: 'default' | 'file';
  errors: string[];
}

/** Parse `.codesentinel.yml`. Invalid files never block a review: defaults are used and errors surfaced. */
export function parseRepoConfig(raw: string | null | undefined): ConfigParseResult {
  if (raw == null || raw.trim() === '') return { config: DEFAULT_CONFIG, source: 'default', errors: [] };
  let data: unknown;
  try {
    data = parseYaml(raw) ?? {};
  } catch (err) {
    return { config: DEFAULT_CONFIG, source: 'default', errors: [`YAML syntax error: ${(err as Error).message.split('\n')[0]}`] };
  }
  const parsed = repoConfigSchema.safeParse(data);
  if (!parsed.success) {
    return {
      config: DEFAULT_CONFIG,
      source: 'default',
      errors: parsed.error.issues.map((i) => `${i.path.join('.') || '(root)'}: ${i.message}`),
    };
  }
  return { config: normalize(parsed.data), source: 'file', errors: [] };
}

