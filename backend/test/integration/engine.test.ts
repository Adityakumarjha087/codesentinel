import { eq } from 'drizzle-orm';
import { describe, expect, it } from 'vitest';
import { findings, llmUsage, repositories, reviews } from '../../src/db/schema.js';
import { FIXTURE_REPOSITORIES, type FixtureRepository } from '../../src/fixtures/repos.js';
import { MockGitHubGateway } from '../../src/github/mock-gateway.js';
import { chunkFile } from '../../src/indexing/indexer.js';
import { MockLlmProvider } from '../../src/llm/mock/provider.js';
import type { LlmProvider, LlmRequest, LlmResponse } from '../../src/llm/types.js';
import { createTestContainer, prEvent } from '../helpers.js';

const payments = FIXTURE_REPOSITORIES.find((r) => r.name === 'payments-api')!;

function repoWith(files: Record<string, string>, changes: Record<string, string | null>, number = 500): FixtureRepository {
  return { ...payments, files: { ...payments.files, ...files }, pullRequests: [{ number, title: 'Test PR', author: 'tester', headRef: `test/${number}`, changes }] };
}

async function runReview(t: Awaited<ReturnType<typeof createTestContainer>>, number = 500) {
  const repos = (t.gateway as unknown as { repos: FixtureRepository[] }).repos;
  const result = await t.container.webhooks.handle('pull_request', undefined, prEvent('acme/payments-api', number, 'opened', repos));
  await t.queue.drain();
  const [review] = await t.container.db.select().from(reviews).where(eq(reviews.id, result.reviewId!));
  const items = await t.container.db.select().from(findings).where(eq(findings.reviewId, result.reviewId!));
  return { review: review!, findings: items };
}

describe('ReviewEngine edge cases', () => {
  it('skips the review when the monthly token budget would be exceeded and posts a notice', async () => {
    const gateway = new MockGitHubGateway([repoWith({}, { 'src/a.ts': 'export const a = eval(x);\n' })]);
    const t = await createTestContainer({ DEFAULT_MONTHLY_TOKEN_BUDGET: '1000' }, { gateway });
    try {
      // Pre-existing spend this month.
      await t.container.webhooks.handle('ping', undefined, {});
      const ev = prEvent('acme/payments-api', 500, 'opened', (gateway as unknown as { repos: FixtureRepository[] }).repos);
      (ev as { action: string }).action = 'labeled';
      await t.container.webhooks.handle('pull_request', undefined, ev); // creates repo without review
      const [repo] = await t.container.db.select().from(repositories);
      await t.container.db.insert(llmUsage).values({ repoId: repo!.id, purpose: 'review:bugs', provider: 'mock', model: 'm', inputTokens: 900, outputTokens: 50, costUsd: 0.01 });
      const { review, findings: items } = await runReview(t);
      expect(review.status).toBe('skipped');
      expect(review.skipReason).toMatch(/Monthly token budget exceeded/);
      expect(items).toHaveLength(0);
      expect(gateway.issueComments.at(-1)!.body).toMatch(/review skipped/);
    } finally {
      await t.close();
    }
  });

  it('skips huge and generated files and reports invalid configs in the summary', async () => {
    const huge = Array.from({ length: 50 }, (_, i) => `export const v${i} = ${i};`).join('\n');
    const gateway = new MockGitHubGateway([
      repoWith(
        { '.codesentinel.yml': 'tone: sarcastic\n' },
        {
          'src/huge.ts': huge,
          'src/gen.ts': '// @generated by protoc\nexport const x = eval(y);\n',
          'src/ok.ts': 'export function ok(a: number) {\n  console.log(a);\n  return a;\n}\n',
          'src/old.ts': null,
        },
      ),
    ]);
    const t = await createTestContainer({ MAX_FILE_CHANGED_LINES: '20' }, { gateway });
    try {
      const { review, findings: items } = await runReview(t);
      expect(review.status).toBe('completed');
      expect(review.filesReviewed).toBe(1);
      expect(review.filesSkipped.map((s) => [s.path, s.reason.split(' ')[0]])).toEqual([
        ['src/huge.ts', 'too'],
        ['src/gen.ts', 'auto-generated'],
        ['src/old.ts', 'file'],
      ]);
      expect(items.map((f) => f.ruleId)).toEqual(['readability/console-log']);
      expect(review.summary).toContain('could not be applied');
      expect(gateway.reviews[0]!.comments[0]!.body).toContain('```suggestion\n\n```'); // delete-line suggestion
    } finally {
      await t.close();
    }
  });

  it('honours disabled rules, max_findings and inline/summary toggles', async () => {
    const gateway = new MockGitHubGateway([
      repoWith(
        { '.codesentinel.yml': 'max_findings: 2\npost_inline_comments: false\nrules:\n  disabled: [readability/console-log]\n' },
        { 'src/many.ts': ['console.log(1);', 'var a = 1;', 'var b = 2;', 'const c = eval(z);', 'if (a == b) {}'].join('\n') + '\n' },
      ),
    ]);
    const t = await createTestContainer({}, { gateway });
    try {
      const { review, findings: items } = await runReview(t);
      expect(items).toHaveLength(2);
      expect(items.map((f) => f.severity).sort()).toEqual(['critical', 'low']);
      expect(items.some((f) => f.ruleId === 'readability/console-log')).toBe(false);
      expect(gateway.reviews).toHaveLength(0);
      expect(review.summaryCommentId).toBeTruthy();
    } finally {
      await t.close();
    }
  });

  it('marks a review failed when every pass errors, and survives partial failures', async () => {
    class FlakyLlm implements LlmProvider {
      readonly name = 'mock' as const;
      readonly model = 'flaky';
      private readonly inner = new MockLlmProvider();
      constructor(private readonly failPasses: string[]) {}
      async complete(req: LlmRequest): Promise<LlmResponse> {
        if (this.failPasses.includes(req.purpose)) throw new Error(`boom ${req.purpose}`);
        return this.inner.complete(req);
      }
    }
    const repo = repoWith({}, { 'src/a.ts': 'export const k = eval(input);\nvar x = 1;\n' });
    const all = await createTestContainer({}, { gateway: new MockGitHubGateway([repo]), llm: new FlakyLlm(['review:bugs', 'review:security', 'review:performance', 'review:readability']) });
    try {
      const { review } = await runReview(all);
      expect(review.status).toBe('failed');
      expect(review.error).toMatch(/All review passes failed/);
    } finally {
      await all.close();
    }
    const partial = await createTestContainer({}, { gateway: new MockGitHubGateway([repo]), llm: new FlakyLlm(['review:readability']) });
    try {
      const { review, findings: items } = await runReview(partial);
      expect(review.status).toBe('completed');
      expect(review.error).toMatch(/Some passes failed: readability/);
      expect(items.map((f) => f.ruleId)).toEqual(['security/code-eval']);
    } finally {
      await partial.close();
    }
  });

  it('drops invalid or hallucinated findings from the model', async () => {
    const liar: LlmProvider = {
      name: 'mock',
      model: 'liar',
      async complete(req) {
        return {
          text: '',
          provider: 'mock',
          model: 'liar',
          usage: { inputTokens: 10, outputTokens: 10 },
          toolCalls: [
            {
              name: 'report_findings',
              arguments: JSON.stringify({
                findings: [
                  { file: 'src/a.ts', line: 1, severity: 'high', title: 'Real', explanation: 'x', rule_id: `r/${req.purpose}`, confidence: 0.9, suggestion: null, end_line: null },
                  { file: 'src/nope.ts', line: 1, severity: 'high', title: 'Wrong file', explanation: 'x', rule_id: 'r', confidence: 1, suggestion: null, end_line: null },
                  { file: 'src/a.ts', line: 999, severity: 'high', title: 'Past EOF', explanation: 'x', rule_id: 'r', confidence: 1, suggestion: null, end_line: null },
                  { file: 'src/a.ts', line: 1, severity: 'catastrophic', title: 'Bad enum', explanation: 'x' },
                ],
              }),
            },
          ],
        };
      },
    };
    const t = await createTestContainer({}, { gateway: new MockGitHubGateway([repoWith({}, { 'src/a.ts': 'export const a = 1;\n' })]), llm: liar });
    try {
      const { findings: items } = await runReview(t);
      expect(items.map((f) => f.title)).toEqual(['Real', 'Real', 'Real', 'Real']);
      expect(new Set(items.map((f) => f.category))).toEqual(new Set(['bug', 'security', 'performance', 'readability']));
    } finally {
      await t.close();
    }
  });

  it('skips PRs with nothing reviewable', async () => {
    const t = await createTestContainer({}, { gateway: new MockGitHubGateway([repoWith({}, { 'package-lock.json': '{}' })]) });
    try {
      const { review } = await runReview(t);
      expect(review).toMatchObject({ status: 'skipped', skipReason: 'No reviewable files in this pull request' });
      // Re-running a finished review is a no-op.
      await t.container.engine.run(review.id);
      await expect(t.container.engine.run('00000000-0000-0000-0000-000000000000')).rejects.toThrow(/not found/);
    } finally {
      await t.close();
    }
  });
});

describe('repository indexing', () => {
  it('chunks by symbols with a module header, and windows unknown languages', async () => {
    const chunks = await chunkFile('src/a.ts', "import x from 'y';\nconst K = 1;\n\nexport function a() {\n  return K;\n}\n");
    expect(chunks.map((c) => [c.kind, c.symbol])).toEqual([
      ['module', null],
      ['function', 'a'],
    ]);
    const md = await chunkFile('README.txt', Array.from({ length: 130 }, (_, i) => `line ${i}`).join('\n'));
    expect(md.map((c) => [c.startLine, c.endLine])).toEqual([
      [1, 60],
      [51, 110],
      [101, 130],
    ]);
  });

  it('searches the pgvector index by similarity and refreshes files incrementally', async () => {
    const t = await createTestContainer();
    try {
      await t.container.webhooks.handle('installation', undefined, {
        action: 'created',
        installation: { id: 9100, account: { login: 'acme' } },
        repositories: [{ id: 700001, name: 'payments-api', full_name: 'acme/payments-api', private: true }],
      });
      await t.queue.drain();
      const [repo] = await t.container.db.select().from(repositories);
      const hits = await t.container.indexer.search(repo!.id, 'record ledger entry insert amount cents', { k: 2 });
      expect(hits[0]!.path).toBe('src/services/ledger.ts');
      expect(hits[0]!.score).toBeGreaterThan(0.2);
      const excluded = await t.container.indexer.search(repo!.id, 'record ledger entry', { k: 5, excludePaths: ['src/services/ledger.ts'] });
      expect(excluded.every((h) => h.path !== 'src/services/ledger.ts')).toBe(true);
      const n = await t.container.indexer.indexFiles(repo!, [{ path: 'src/services/ledger.ts', content: 'export function totallyDifferent() {}\n' }]);
      expect(n).toBe(1);
    } finally {
      await t.close();
    }
  });
});
