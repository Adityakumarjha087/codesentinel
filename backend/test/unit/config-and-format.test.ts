import { describe, expect, it } from 'vitest';
import { formatInlineComment, formatSummary } from '../../src/github/comments.js';
import { signPayload, verifySignature } from '../../src/github/signature.js';
import { estimateTokens } from '../../src/lib/tokens.js';
import { costUsd, priceFor } from '../../src/llm/pricing.js';
import { classifyFinding } from '../../src/review/acceptance.js';
import { createIgnoreMatcher, DEFAULT_CONFIG, DEFAULT_IGNORES, looksGenerated, parseRepoConfig } from '../../src/review/config.js';
import { loadEnv } from '../../src/config/env.js';

describe('.codesentinel.yml parsing', () => {
  it('uses defaults when the file is missing', () => {
    expect(parseRepoConfig(null)).toEqual({ config: DEFAULT_CONFIG, source: 'default', errors: [] });
    expect(DEFAULT_CONFIG).toMatchObject({ tone: 'neutral', severityThreshold: 'low', maxFindings: 30 });
  });

  it('parses rules, ignored paths, threshold and tone', () => {
    const { config, source, errors } = parseRepoConfig(`
tone: strict
severity_threshold: high
max_findings: 5
passes:
  readability: false
ignore: ["docs/**"]
rules:
  disabled: [bugs/loose-equality]
  instructions: ["Prefer early returns"]
`);
    expect(source).toBe('file');
    expect(errors).toEqual([]);
    expect(config).toMatchObject({
      tone: 'strict',
      severityThreshold: 'high',
      maxFindings: 5,
      ignore: ['docs/**'],
      passes: { bugs: true, security: true, performance: true, readability: false },
      rules: { disabled: ['bugs/loose-equality'], instructions: ['Prefer early returns'] },
    });
  });

  it('reports schema and YAML errors but falls back to defaults', () => {
    const invalid = parseRepoConfig('tone: sarcastic\nunknown_key: 1');
    expect(invalid.source).toBe('default');
    expect(invalid.errors.join(' ')).toMatch(/tone/);
    const broken = parseRepoConfig('tone: [unclosed');
    expect(broken.errors[0]).toMatch(/YAML syntax error/);
  });

  it('matches ignore globs and default generated paths', () => {
    const ignored = createIgnoreMatcher(DEFAULT_IGNORES);
    expect(ignored('package-lock.json')).toBe(true);
    expect(ignored('web/dist/app.js')).toBe(true);
    expect(ignored('assets/logo.png')).toBe(true);
    expect(ignored('src/app.ts')).toBe(false);
    expect(createIgnoreMatcher([])('anything')).toBe(false);
  });

  it('detects generated content', () => {
    expect(looksGenerated('// Code generated by protoc. DO NOT EDIT.\npackage x')).toBe(true);
    expect(looksGenerated('x'.repeat(6000))).toBe(true);
    expect(looksGenerated('const a = 1;\n')).toBe(false);
    expect(looksGenerated(null)).toBe(false);
  });
});

describe('GitHub comment formatting', () => {
  const finding = {
    severity: 'high' as const,
    category: 'security' as const,
    title: 'SQL injection',
    explanation: 'Use parameters.',
    suggestion: 'db.query("SELECT 1 WHERE id = $1", [id]);',
    ruleId: 'security/sql-injection',
    confidence: 0.9,
  };

  it('renders inline comments with suggestion blocks', () => {
    const body = formatInlineComment(finding);
    expect(body).toContain('`HIGH` · Security · `security/sql-injection`');
    expect(body).toContain('```suggestion\ndb.query("SELECT 1 WHERE id = $1", [id]);\n```');
    expect(body).toContain('Confidence 90%');
    expect(formatInlineComment({ ...finding, suggestion: null })).not.toContain('```suggestion');
  });

  it('renders a summary with counts, skipped files and config errors', () => {
    const body = formatSummary({
      findings: [finding],
      outOfDiff: [{ ...finding, severity: 'low', category: 'readability' }],
      filesReviewed: 2,
      skipped: [{ path: 'package-lock.json', reason: 'lock file' }],
      config: { ...DEFAULT_CONFIG, tone: 'friendly' },
      configErrors: ['tone: invalid'],
      passes: ['Security'],
      usage: { inputTokens: 100, outputTokens: 20, costUsd: 0.0012, model: 'm' },
      dashboardUrl: 'http://x/',
    });
    expect(body).toContain('Thanks for the PR!');
    expect(body).toContain('| HIGH | 1 |');
    expect(body).toContain('`package-lock.json`: lock file');
    expect(body).toContain('could not be applied');
    expect(body).toContain('120 tokens');
    expect(body).toContain('outside the diff');
    const clean = formatSummary({ findings: [], outOfDiff: [], filesReviewed: 1, skipped: [], config: { ...DEFAULT_CONFIG, tone: 'strict' }, configErrors: [], passes: [], usage: { inputTokens: 0, outputTokens: 0, costUsd: 0, model: 'm' } });
    expect(clean).toContain('No issues found.');
  });
});

describe('webhook signatures', () => {
  it('accepts valid and rejects tampered or missing signatures', () => {
    const sig = signPayload('s3cret', '{"a":1}');
    expect(sig).toMatch(/^sha256=[0-9a-f]{64}$/);
    expect(verifySignature('s3cret', '{"a":1}', sig)).toBe(true);
    expect(verifySignature('s3cret', '{"a":2}', sig)).toBe(false);
    expect(verifySignature('other', '{"a":1}', sig)).toBe(false);
    expect(verifySignature('s3cret', '{"a":1}', undefined)).toBe(false);
    expect(verifySignature('s3cret', '{"a":1}', 'sha1=abc')).toBe(false);
  });
});

describe('cost and tokens', () => {
  it('estimates tokens and prices models', () => {
    expect(estimateTokens('')).toBe(0);
    expect(estimateTokens('abcdefgh')).toBe(2);
    expect(priceFor('anthropic', 'claude-opus-5-5')).toEqual({ input: 4, output: 20 });
    expect(priceFor('ollama', 'llama3')).toEqual({ input: 0, output: 0 });
    expect(priceFor('openai', 'unknown-model')).toEqual({ input: 1, output: 5 });
    expect(costUsd('anthropic', 'claude-opus-5-5', 1_000_000, 100_000)).toBe(6);
  });
});

describe('acceptance classification', () => {
  it('classifies applied suggestions, other fixes and untouched findings', () => {
    const f = { suggestion: 'const x = 1;', codeSnippet: 'var x = 1;' };
    expect(classifyFinding(f, 'let a;\nconst x = 1;\n')).toBe('accepted');
    expect(classifyFinding(f, 'let x = 2;\n')).toBe('resolved');
    expect(classifyFinding(f, 'var x = 1;\n')).toBe('open');
    expect(classifyFinding(f, null)).toBe('resolved');
    expect(classifyFinding({ suggestion: '', codeSnippet: 'console.log(1)' }, 'const y = 2;')).toBe('accepted');
  });
});

describe('environment validation', () => {
  it('applies offline defaults', () => {
    const env = loadEnv({});
    expect(env).toMatchObject({ LLM_PROVIDER: 'mock', GITHUB_MODE: 'mock', EMBEDDING_PROVIDER: 'hash', QUEUE_MODE: 'inline', RUN_WORKER: true });
  });

  it('requires credentials for real providers and live GitHub', () => {
    expect(() => loadEnv({ LLM_PROVIDER: 'anthropic' })).toThrow(/API key is required/);
    expect(() => loadEnv({ GITHUB_MODE: 'live' })).toThrow(/GITHUB_APP_ID/);
    expect(() => loadEnv({ QUEUE_MODE: 'bullmq' })).toThrow(/REDIS_URL/);
    expect(() => loadEnv({ NODE_ENV: 'production' })).toThrow(/JWT_SECRET/);
    expect(() => loadEnv({ EMBEDDING_PROVIDER: 'openai' })).toThrow(/OPENAI_API_KEY/);
    expect(loadEnv({ LLM_PROVIDER: 'anthropic', ANTHROPIC_API_KEY: 'k', RUN_WORKER: 'false' })).toMatchObject({ LLM_PROVIDER: 'anthropic', RUN_WORKER: false });
  });
});
